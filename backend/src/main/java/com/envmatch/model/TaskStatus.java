package com.envmatch.model;

/**
 * 对比分析任务状态枚举。
 */
public enum TaskStatus {
    
    /** 排队中，待处理。任务刚创建，文件已上传成功，但还未被后台线程池拉起执行。 */
    PENDING,
    
    /** 执行中。正在进行元数据探测、视频抽帧/感知采样、压缩以及多模态模型调用分析。 */
    PROCESSING,
    
    /** 已完成。分析全部成功，维度得分与总结数据均已正确写回数据库。 */
    COMPLETED,
    
    /** 已失败。可能由于视频解析失败、模型调用超时或出错、数据库写回异常等原因终止。 */
    FAILED
}
